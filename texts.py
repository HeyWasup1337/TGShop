def t(lang: str, key: str) -> str:
    lang_dict = TEXTS.get(lang, TEXTS["ru"])
    return lang_dict.get(key, TEXTS["ru"].get(key, key))


def fmt_price(price: int) -> str:
    return f"{int(price or 0):,}".replace(",", " ")


def cur_label(lang: str, currency: str) -> str:
    if currency == "XTR":
        return "⭐️"
    return t(lang, "cur_usd" if currency == "USD" else "cur_uzs")


def status_label(lang: str, status: str) -> str:
    return t(lang, f"status_{status}")